#!/usr/bin/env node
/**
 * The SDK ships a copy of the authoritative contract (backend/src/contracts) so it has no dependency on the
 * backend. This copies it, or with --check fails when the copy differs (run in CI), so the two never drift.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../../../backend/src/contracts');
const dst = path.resolve(here, '../src/contract');
const files = ['common.ts', 'events.v1.ts', 'aiAdapter.v1.ts', 'conformance/aiAdapterConformance.ts'];
const header = (f) => `// GENERATED by sdk/ai-adapter/scripts/sync-contract.mjs from backend/src/contracts/${f}. Do not edit here.\n`;
const check = process.argv.includes('--check');
let drift = 0;
for (const f of files) {
  const want = header(f) + fs.readFileSync(path.join(src, f), 'utf8');
  const out = path.join(dst, f);
  if (check) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (have !== want) {
      console.error(`DRIFT: sdk/ai-adapter/src/contract/${f} differs from backend/src/contracts/${f}; run npm run sync-contract`);
      drift++;
    }
  } else {
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, want);
    console.log(`copied ${f}`);
  }
}
if (check) console.log(drift ? `${drift} contract file(s) out of date` : 'SDK contract copy matches the backend');
process.exit(drift ? 1 : 0);
