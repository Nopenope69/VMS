#!/usr/bin/env node
/**
 * Generates docs/ai/MODEL_CARD_<key>.md from the pinned model entry and an evaluation result
 * (coco-eval.mjs output). A card is marked NOT EVALUATED unless the evaluation is on real site data
 * (--real-site-data) with enough labelled frames per class (default 500, action plan P2.10).
 *
 *   node tools/eval/model-card.mjs --model yolox-tiny --metrics metrics.json --dataset "name" \
 *        [--real-site-data] [--min-per-class 500] [--out docs/ai/MODEL_CARD_yolox-tiny.md]
 */
import fs from 'fs';
import path from 'path';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const args = process.argv.slice(2);
const get = (k, d) => {
  const i = args.indexOf(k);
  return i >= 0 ? args[i + 1] : d;
};
const key = get('--model');
const metricsPath = get('--metrics');
if (!key || !metricsPath) {
  console.error('usage: model-card.mjs --model <lock key> --metrics metrics.json --dataset "name" [--real-site-data] [--out file]');
  process.exit(2);
}
const lock = JSON.parse(fs.readFileSync(path.join(REPO, 'scripts/models/models.lock.json'), 'utf8'));
const m = lock.models.find((x) => x.key === key);
if (!m) throw new Error(`unknown model ${key}`);
const metrics = JSON.parse(fs.readFileSync(metricsPath, 'utf8'));
const dataset = get('--dataset', 'unnamed dataset');
const realSite = args.includes('--real-site-data');
const minPerClass = Number(get('--min-per-class', '500'));
const V1 = ['person', 'bicycle', 'motorcycle', 'car', 'bus', 'truck'];

const v1Rows = V1.map((c) => [c, metrics.perClass[c]]);
const enough = v1Rows.filter(([, v]) => v && v.groundTruth >= minPerClass).map(([c]) => c);
const evaluated = realSite && enough.length > 0;
const fmt = (v) => (v === null || v === undefined ? 'n/a' : typeof v === 'number' ? (Number.isInteger(v) ? String(v) : v.toFixed(3)) : String(v));

const lines = [];
lines.push(`# Model card: ${m.name} ${m.version}`);
lines.push('');
lines.push('<!-- Generated by tools/eval/model-card.mjs. Do not edit by hand; regenerate from an evaluation run. -->');
lines.push('');
if (!evaluated) {
  lines.push('> **NOT EVALUATED on real site data.** The numbers below come from ' + `"${dataset}"` + ', which is not a');
  lines.push(`> labelled set of real-site footage with at least ${minPerClass} instances per class. AI events from this`);
  lines.push('> model are shown as experimental in the operator console until a real evaluation (action plan P2.10) is');
  lines.push('> committed here.');
} else {
  lines.push(`> Evaluated on real site data ("${dataset}"). Classes with at least ${minPerClass} labelled instances: ${enough.join(', ')}.`);
}
lines.push('');
lines.push('## Identity');
lines.push('');
lines.push('| Field | Value |');
lines.push('| --- | --- |');
lines.push(`| Model | ${m.name} |`);
lines.push(`| Version | ${m.version} |`);
lines.push(`| SHA-256 | \`${m.sha256}\` |`);
lines.push(`| Artefact | ${m.url} (${m.sizeBytes} bytes) |`);
lines.push(`| Code / weights licence | ${m.codeLicense} / ${m.weightLicense} |`);
lines.push(`| Weights source | ${m.weightsSource} |`);
lines.push(`| Training data | ${m.trainingData.source} (${m.trainingData.license}); ${m.trainingData.provenance} |`);
lines.push(`| Runtime | ${m.runtimeConfig.runtime} ${m.runtimeConfig.runtimeVersion ?? ''}, ${m.runtimeConfig.executionProvider} |`);
lines.push(`| Input | ${m.runtimeConfig.inputWidth}x${m.runtimeConfig.inputHeight} ${m.runtimeConfig.colorSpace}, letterbox ${m.runtimeConfig.letterbox ? `(${m.runtimeConfig.padPosition}, pad ${m.runtimeConfig.padValue})` : 'no'} |`);
lines.push(`| Decoder | ${m.modelSignature.decoder} |`);
lines.push('');
lines.push('## Intended use and limits');
lines.push('');
lines.push('Detects the VigilOne v1 classes (person, bicycle, motorcycle, car, bus, truck) in sampled CCTV frames to drive');
lines.push('tripwire, loitering and object rules. Other COCO classes are dropped before tracking. Not for identifying');
lines.push('people. COCO-trained: accuracy on Indian site conditions (night IR, rain, low mounting angles, crowded');
lines.push('two-wheeler traffic) is unknown until measured.');
lines.push('');
lines.push('## Evaluation');
lines.push('');
lines.push(`Dataset: ${dataset}. Images: ${metrics.images}. Ground-truth boxes: ${metrics.groundTruth}. Operating threshold: ${metrics.scoreThreshold}.`);
lines.push(`Footage duration: ${metrics.durationHours ? metrics.durationHours + ' h' : 'not given (FP per hour not computed)'}.`);
lines.push('');
lines.push('| Class | GT | AP@[.5:.95] | AP@.5 | Precision | Recall | FP | FP/hour |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const [c, v] of Object.entries(metrics.perClass)) {
  lines.push(`| ${c}${V1.includes(c) ? '' : ' (not a v1 class)'} | ${fmt(v.groundTruth)} | ${fmt(v.ap)} | ${fmt(v.ap50)} | ${fmt(v.precision)} | ${fmt(v.recall)} | ${fmt(v.fp)} | ${fmt(v.fpPerHour)} |`);
}
lines.push('');
lines.push(`mAP@[.5:.95] ${fmt(metrics.mAP)}, mAP@.5 ${fmt(metrics.mAP50)} (over classes with ground truth).`);
lines.push('');
lines.push('Metrics: tools/eval/coco-eval.mjs (checked against pycocotools COCOeval). Detections: tools/eval/detect-images.mjs');
lines.push('(the ai-worker engine and letterbox path used in production).');
lines.push('');

const outPath = get('--out', path.join(REPO, 'docs', 'ai', `MODEL_CARD_${key}.md`));
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`wrote ${outPath} (${evaluated ? 'EVALUATED' : 'NOT EVALUATED'})`);
