#!/usr/bin/env node
/**
 * Regenerates the BENCH_RESULTS block of docs/operations/HARDWARE_COMPATIBILITY_MATRIX.md from
 * real-camera bench reports in docs/operations/bench-results/. SIMULATED_* reports are ignored.
 *   node scripts/bench/update-matrix.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const resultsDir = path.join(root, 'docs/operations/bench-results');
const matrixPath = path.join(root, 'docs/operations/HARDWARE_COMPATIBILITY_MATRIX.md');
const START = '<!-- BENCH_RESULTS:START (generated by scripts/bench/update-matrix.mjs; do not edit by hand) -->';
const END = '<!-- BENCH_RESULTS:END -->';

export function renderRows(reports) {
  const real = reports.filter((r) => r.schema === 'vigilone.bench.v1' && r.sourceKind === 'camera' && r.simulated === false);
  if (real.length === 0) return 'No real-camera bench reports have been committed yet.';
  const rows = real
    .sort((a, b) => a.startedAtUtc.localeCompare(b.startedAtUtc))
    .map((r) => {
      const d = r.camera?.onvif?.deviceInfo || {};
      const v = r.steps?.rtsp?.video || {};
      return `| ${d.manufacturer ?? 'unknown'} | ${d.model ?? 'unknown'} | ${d.firmwareVersion ?? 'unknown'} | ${v.codec ?? '?'} ${v.width ?? '?'}x${v.height ?? '?'} @ ${v.fps ? v.fps.toFixed(1) : '?'} | ${r.requested.durationSec} s | **${r.verdict === 'PASS' ? 'Validated' : 'FAILED'}** | ${r.startedAtUtc.slice(0, 10)} | \`${r._file}\` |`;
    });
  return ['| Manufacturer | Model | Firmware | Stream | Record | Result | Date | Report |', '| --- | --- | --- | --- | --- | --- | --- | --- |', ...rows].join('\n');
}

function main() {
  const reports = fs.existsSync(resultsDir)
    ? fs
        .readdirSync(resultsDir)
        .filter((f) => f.endsWith('.json') && !f.startsWith('SIMULATED_'))
        .map((f) => ({ ...JSON.parse(fs.readFileSync(path.join(resultsDir, f), 'utf8')), _file: `bench-results/${f}` }))
    : [];
  const doc = fs.readFileSync(matrixPath, 'utf8');
  const s = doc.indexOf(START);
  const e = doc.indexOf(END);
  if (s < 0 || e < 0) throw new Error('matrix is missing BENCH_RESULTS markers');
  const next = `${doc.slice(0, s)}${START}\n${renderRows(reports)}\n${END}${doc.slice(e + END.length)}`;
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error('HARDWARE_COMPATIBILITY_MATRIX.md bench block is stale; run node scripts/bench/update-matrix.mjs');
      process.exit(1);
    }
    console.log('bench block up to date');
    return;
  }
  fs.writeFileSync(matrixPath, next);
  console.log(`matrix updated from ${reports.length} real-camera report(s)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
